import { useEffect, useRef, useState } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { activeChatKey, createChat, streamChatMessage } from './api'
import { ChatComposer } from './ChatComposer'
import { ChatHeading } from './ChatHeading'
import { ChatMessageList } from './ChatMessageList'
import type { ChatMessage } from './types'

interface ChatConversationProps {
  chatId: string
  initialMessages: ChatMessage[]
}

function appendToLastMessage(messages: ChatMessage[], token: string): ChatMessage[] {
  const last = messages[messages.length - 1]
  return [...messages.slice(0, -1), { ...last, text: last.text + token }]
}

// The interrupt question is not generated by the model, so it arrives whole instead
// of as tokens. It fills the empty reply bubble, or gets its own one after a text reply.
function addInterruptMessage(messages: ChatMessage[], text: string): ChatMessage[] {
  const last = messages[messages.length - 1]
  if (last.role === 'ai' && last.text === '') {
    return [...messages.slice(0, -1), { ...last, text }]
  }
  return [...messages, { id: crypto.randomUUID(), role: 'ai', text, created_at: null }]
}

// Stamps the AI messages of the current turn (the ones after turnStart).
function setTurnCreatedAt(
  messages: ChatMessage[],
  turnStart: number,
  createdAt: number,
): ChatMessage[] {
  return messages.map((message, index) =>
    index > turnStart && message.role === 'ai' && message.created_at === null
      ? { ...message, created_at: createdAt }
      : message,
  )
}

function dropEmptyLastMessage(messages: ChatMessage[]): ChatMessage[] {
  const last = messages[messages.length - 1]
  return last && last.role === 'ai' && last.text === '' ? messages.slice(0, -1) : messages
}

export function ChatConversation({ chatId, initialMessages }: ChatConversationProps) {
  const [messages, setMessages] = useState<ChatMessage[]>(initialMessages)
  const [isStreaming, setIsStreaming] = useState(false)
  const [sendError, setSendError] = useState<string | null>(null)
  const abortRef = useRef<AbortController | null>(null)
  const queryClient = useQueryClient()

  // The new chat replaces the active one in the cache; ChatPage then remounts
  // this component by the new chat id, which resets the local messages.
  const newChatMutation = useMutation({
    mutationFn: createChat,
    onSuccess: (data) => queryClient.setQueryData(activeChatKey, data),
  })

  async function handleSend(text: string): Promise<void> {
    const createdAt = Date.now() / 1000
    // Index of the human message being sent; sending is blocked while streaming,
    // so `messages` here is up to date.
    const turnStart = messages.length
    setMessages((current) => [
      ...current,
      { id: crypto.randomUUID(), role: 'human', text, created_at: createdAt },
      { id: crypto.randomUUID(), role: 'ai', text: '', created_at: null },
    ])
    setIsStreaming(true)
    setSendError(null)
    const controller = new AbortController()
    abortRef.current = controller
    let isDone = false
    try {
      for await (const event of streamChatMessage(chatId, text, controller.signal)) {
        if (event.event === 'token') {
          setMessages((current) => appendToLastMessage(current, event.text))
        } else if (event.event === 'interrupt') {
          setMessages((current) => addInterruptMessage(current, event.text))
        } else if (event.event === 'done') {
          isDone = true
          setMessages((current) => setTurnCreatedAt(current, turnStart, event.created_at))
        } else {
          throw new Error(event.text)
        }
      }
      // The connection closed without `done` or `error`, e.g. the server went down.
      if (!isDone) {
        throw new Error('The reply was interrupted. Try again.')
      }
    } catch (error) {
      if (controller.signal.aborted) {
        setMessages((current) => setTurnCreatedAt(current, turnStart, Date.now() / 1000))
      } else {
        setSendError(error instanceof Error ? error.message : 'Could not send message')
      }
    } finally {
      abortRef.current = null
      setMessages(dropEmptyLastMessage)
      setIsStreaming(false)
    }
  }

  function handleStop(): void {
    abortRef.current?.abort()
  }

  // Effect is needed: leaving the page must close the open stream, otherwise the
  // backend keeps generating a reply nobody will see.
  useEffect(() => {
    return () => abortRef.current?.abort()
  }, [])

  return (
    <>
      <ChatHeading>
        <button
          type="button"
          className="secondary-button"
          onClick={() => newChatMutation.mutate()}
          disabled={isStreaming || newChatMutation.isPending}
        >
          New chat
        </button>
      </ChatHeading>

      {sendError || newChatMutation.error ? (
        <div className="inline-error" role="alert">
          {sendError ?? newChatMutation.error?.message}
        </div>
      ) : null}

      <ChatMessageList messages={messages} isStreaming={isStreaming} />

      <ChatComposer
        isStreaming={isStreaming}
        onSend={(text) => void handleSend(text)}
        onStop={handleStop}
      />
    </>
  )
}
